"""Frozen fixture restoration must work on clean checkouts and fail on drift."""
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location('hts_fixture_generator', ROOT / 'scripts/fetch-hts-test-data.py')
generator = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(generator)


class FixtureRestorationTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        base = Path(temporary.name)
        self.data, self.generated = base / 'data', base / 'generated'
        self.data.mkdir(); self.generated.mkdir()
        for name, value in [('common/generated.bgz', b'Frozen binary\0fixture\n'),
                            ('upstream/version/input.vcf', b'Frozen upstream fixture\n')]:
            generator.write(self.generated / name, value)
        self.manifest = {'files': generator.inventory(self.generated)}
        self.manifest_raw = json.dumps(self.manifest).encode()
        generator.write(self.data / 'manifest.json', self.manifest_raw)
        generator.write(self.data / 'upstream/version/input.vcf', b'Frozen upstream fixture\n')
        data_patch = patch.object(generator, 'DATA', self.data)
        data_patch.start(); self.addCleanup(data_patch.stop)

    def test_missing_frozen_file_is_restored_without_manifest_change(self):
        generator.materialize_frozen(self.generated, self.manifest)
        self.assertEqual(generator.inventory(self.data), self.manifest['files'])
        self.assertEqual((self.data / 'manifest.json').read_bytes(), self.manifest_raw)
        generator.materialize_frozen(self.generated, self.manifest)
        self.assertEqual(generator.inventory(self.data), self.manifest['files'])

    def test_changed_existing_file_rejected_before_restoration(self):
        generator.write(self.data / 'upstream/version/input.vcf', b'Changed existing data')
        with self.assertRaisesRegex(RuntimeError, 'Existing fixtures differ'):
            generator.materialize_frozen(self.generated, self.manifest)
        self.assertFalse((self.data / 'common/generated.bgz').exists())

    def test_extra_existing_file_rejected_before_restoration(self):
        generator.write(self.data / 'common/unlisted.txt', b'Unlisted input')
        with self.assertRaisesRegex(RuntimeError, 'Existing fixtures differ'):
            generator.materialize_frozen(self.generated, self.manifest)
        self.assertFalse((self.data / 'common/generated.bgz').exists())

    def test_generator_drift_rejected_before_restoration(self):
        generator.write(self.generated / 'common/generated.bgz', b'Different generated bytes')
        with self.assertRaisesRegex(RuntimeError, 'Regenerated fixtures differ'):
            generator.materialize_frozen(self.generated, self.manifest)
        self.assertFalse((self.data / 'common/generated.bgz').exists())


if __name__ == '__main__':
    unittest.main()
